# Submit drivers to Microsoft to be signed with EV certificate.
#
# Usage: attestation.sh [arch] [config] [Signed_XXXX.zip]
#
#   arch    x64 (default) | arm64
#   config  Debug (default) | Release
#
# 1: Compile project with codesign (out/build/<arch>-<config>)
# 2: Run this script with no zip argument, ie:
#        contrib/windows/attestation.sh x64 Release
#    it will create disk1/OpenZFS-<arch>-<config>.cab
# 3: Go to URL and add "New Hardware Submission" upload the .cab
# 4: Wait for the signature, and "Download signed files"
#    Can be hard to find, click small "More" on the upload line.
# 5: Run script again with downloaded filename as argument, ie:
#        contrib/windows/attestation.sh x64 Release Signed_XXXX.zip
#    MS signed binaries are copied into out/ directory, do not compile again
# 6: Run Inno Setup and produce installer.
#
# 20231212 lundman
#
# The signing certificate defaults to lundman's, set OPENZFS_ATTEST_SHA1
# to the SHA1 thumbprint of your own to override.

set -euo pipefail

ARCH="${1:-x64}"
CONFIG="${2:-Debug}"
ZIP="${3:-}"

case "$ARCH" in
	x64|arm64) ;;
	*) echo "Unknown arch '$ARCH' (x64 or arm64)"; exit 1 ;;
esac
case "$CONFIG" in
	Debug|Release) ;;
	*) echo "Unknown config '$CONFIG' (Debug or Release)"; exit 1 ;;
esac

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"

FLAVOUR="${ARCH}-${CONFIG}"
BUILD="out/build/${FLAVOUR}"
CERT="${OPENZFS_ATTEST_SHA1:-20564273046A323E710BFDC5C9CC22E7392F8049}"

if [ ! -d "$BUILD" ]; then
	echo "Build dir not found: $BUILD"
	exit 1
fi

WDK_BASE_PATH="/c/Program Files (x86)/Windows Kits/10/bin"
LATEST_VERSION=$(ls "$WDK_BASE_PATH" | grep -E '^[0-9]+\.[0-9]+\.[0-9]+\.[0-9]+$' | sort -V | tail -n 1)
SIGNTOOL="$WDK_BASE_PATH/$LATEST_VERSION/x64/signtool.exe"

if [ -z "$ZIP" ]; then
	DDF="$(mktemp)"
	trap 'rm -f "$DDF"' EXIT

	# makecab wants backslash paths relative to the repo root
	W="out\\build\\${FLAVOUR}"
	cat > "$DDF" <<EOF
;*** OpenZFS.ddf, generated by attestation.sh
;
.OPTION EXPLICIT
.Set CabinetFileCountThreshold=0
.Set FolderFileCountThreshold=0
.Set FolderSizeThreshold=0
.Set MaxCabinetSize=0
.Set MaxDiskFileCount=0
.Set MaxDiskSize=0
.Set CompressionType=MSZIP
.Set Cabinet=on
.Set Compress=on
.Set CabinetNameTemplate=OpenZFS-${FLAVOUR}.cab
; Your cab file should not have files at the root level,
; and each driver package must be in a separate subfolder.
.Set DestinationDir=OpenZFS
${W}\\module\\os\\windows\\driver\\OpenZFS.Inf
${W}\\module\\os\\windows\\driver\\OpenZFS.sys
${W}\\module\\os\\windows\\driver\\OpenZFS.pdb
${W}\\module\\os\\windows\\driver\\OpenZFS.cat
${W}\\module\\os\\windows\\driver\\OpenZFS.man
${W}\\module\\os\\windows\\zvol\\driver\\OpenZVOL.sys
${W}\\module\\os\\windows\\zvol\\driver\\OpenZVOL.Inf
${W}\\module\\os\\windows\\zvol\\driver\\OpenZVOL.pdb
${W}\\module\\os\\windows\\zvol\\driver\\OpenZVOL.cat
EOF

	makecab -f "$(cygpath -w "$DDF")"

	"$SIGNTOOL" sign -v -as -fd sha256 -td sha256 -sha1 "$CERT" \
	    -tr http://ts.ssl.com "disk1/OpenZFS-${FLAVOUR}.cab"

	echo "Now go to https://partner.microsoft.com/en-us/dashboard/hardware/driver/New#?productId=14183878782569539"
	echo "Sign disk1/OpenZFS-${FLAVOUR}.cab, download new package, run:"
	echo " $0 $ARCH $CONFIG Signed_XXXX.zip"

	exit 0
fi

rm -rf drivers
unzip "$ZIP"

DRV="$BUILD/module/os/windows/driver"
ZVOL="$BUILD/module/os/windows/zvol/driver"

cp drivers/OpenZFS/OpenZFS.Inf "$DRV/"
cp drivers/OpenZFS/OpenZFS.cat "$DRV/"
cp drivers/OpenZFS/OpenZFS.man "$DRV/"
cp drivers/OpenZFS/OpenZFS.sys "$DRV/"
cp drivers/OpenZFS/OpenZVOL.sys "$ZVOL/"
cp drivers/OpenZFS/OpenZVOL.cat "$ZVOL/"
cp drivers/OpenZFS/OpenZVOL.Inf "$ZVOL/"

echo "Populating symstore ... "
contrib/windows/symstore.sh "$ARCH" "$CONFIG"

echo ""
echo "Now run Inno Setup to produce installer"
